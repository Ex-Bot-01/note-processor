#[test]
fn every_entry_is_written_exactly_once_under_adversarial_buckets() {
    let mut entries = many('m', 13);
    entries.extend(many('0', 5));
    entries.extend(many('ß', 4));
    entries.extend(many('#', 2));

    let rendered = render(&entries, &config(4));

    let mut file_names = names(&rendered);
    let sorted_names = {
        let mut sorted = file_names.clone();
        sorted.sort_unstable();
        sorted.dedup();
        sorted
    };
    file_names.sort_unstable();
    assert_eq!(
        file_names, sorted_names,
        "duplicate file names would lose entries"
    );

    // `INDEX.md` holds no notes, so the shards alone must account for every entry.
    let mut listed: Vec<String> = Vec::new();
    for (name, _) in rendered.iter().skip(1) {
        listed.extend(titles_in(contents(&rendered, name)));
    }
    // Expected order is the render's own: bucket (`0-9`, `a-z`, then `#` last), then lowercased
    // title. A plain lowercase sort would put `#note` before `0note`, i.e. the `#` bucket first.
    let mut expected: Vec<String> = entries.iter().map(|note| note.title.clone()).collect();
    expected.sort_by(|left, right| {
        bucket_rank(left)
            .cmp(&bucket_rank(right))
            .then_with(|| left.to_lowercase().cmp(&right.to_lowercase()))
    });
    assert_eq!(
        listed.len(),
        expected.len(),
        "an entry was dropped or doubled"
    );
    assert_eq!(listed, expected);
}

