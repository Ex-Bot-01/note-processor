#[test]
fn shards_over_threshold_and_index_links_them() {
    let entries = vec![
        entry("Alpha", "a.md", "1 B", &[], 0, 0),
        entry("Bravo", "b.md", "1 B", &[], 0, 0),
        entry("Mike", "m.md", "1 B", &[], 0, 0),
        entry("November", "n.md", "1 B", &[], 0, 0),
        entry("Oscar", "o.md", "1 B", &[], 0, 0),
        entry("Victor", "v.md", "1 B", &[], 0, 0),
        entry("Zulu", "z.md", "1 B", &[], 0, 0),
    ];

    let rendered = render(&entries, &config(3));

    assert_eq!(
        names(&rendered),
        ["INDEX.md", "INDEX-a-m.md", "INDEX-n-v.md", "INDEX-z-z.md"]
    );
    // The entry point is links only: no note line may survive in it.
    assert_eq!(
        body(contents(&rendered, "INDEX.md")),
        "- [a–m](INDEX-a-m.md)\n- [n–v](INDEX-n-v.md)\n- [z–z](INDEX-z-z.md)\n"
    );
    for (name, _) in &rendered {
        let file = contents(&rendered, name);
        assert_eq!(
            file.matches("# INDEX").count(),
            1,
            "{name} must carry the header exactly once"
        );
    }
    assert_eq!(
        titles_in(contents(&rendered, "INDEX-a-m.md")),
        ["Alpha", "Bravo", "Mike"]
    );
    assert_eq!(
        titles_in(contents(&rendered, "INDEX-n-v.md")),
        ["November", "Oscar", "Victor"]
    );
    assert_eq!(titles_in(contents(&rendered, "INDEX-z-z.md")), ["Zulu"]);
}

#[test]
fn shard_boundary_splits_mid_bucket() {
    // Three `a` notes and one `b` note with a threshold of two: the first cut lands inside the
    // `a` bucket, so the second shard starts where its predecessor stopped.
    let entries = vec![
        entry("alpha one", "a1.md", "1 B", &[], 0, 0),
        entry("alpha two", "a2.md", "1 B", &[], 0, 0),
        entry("alpha three", "a3.md", "1 B", &[], 0, 0),
        entry("beta four", "b1.md", "1 B", &[], 0, 0),
    ];

    let rendered = render(&entries, &config(2));

    assert_eq!(
        names(&rendered),
        ["INDEX.md", "INDEX-a-a.md", "INDEX-a-b.md"]
    );
    assert_eq!(
        body(contents(&rendered, "INDEX.md")),
        "- [a–a](INDEX-a-a.md)\n- [a–b](INDEX-a-b.md)\n"
    );
    // The order inside a shard is the render's total order — lowercased title, then `rel` — so
    // `alpha three` precedes `alpha two`, not the order the entries were handed over in.
    assert_eq!(
        titles_in(contents(&rendered, "INDEX-a-a.md")),
        ["alpha one", "alpha three"]
    );
    assert_eq!(
        titles_in(contents(&rendered, "INDEX-a-b.md")),
        ["alpha two", "beta four"]
    );
}

#[test]
fn repeat_range_shards_get_a_positional_suffix() {
    // One bucket far larger than the threshold: every shard spans `m`–`m`, so the name and the
    // label both carry the walk position, or half the catalog would be written over itself.
    let rendered = render(&many('m', 7), &config(3));

    assert_eq!(
        names(&rendered),
        [
            "INDEX.md",
            "INDEX-m-m.md",
            "INDEX-m-m-2.md",
            "INDEX-m-m-3.md"
        ]
    );
    assert_eq!(
        body(contents(&rendered, "INDEX.md")),
        "- [m–m](INDEX-m-m.md)\n- [m–m #2](INDEX-m-m-2.md)\n- [m–m #3](INDEX-m-m-3.md)\n"
    );

    // A normal bucket in front of an oversized one shifts the suffix onto the second repeat.
    let mut mixed = vec![entry("Anvil", "anvil.md", "1 B", &[], 0, 0)];
    mixed.extend(many('m', 7));
    let rendered = render(&mixed, &config(3));

    assert_eq!(
        names(&rendered),
        ["INDEX.md", "INDEX-a-m.md", "INDEX-m-m.md", "INDEX-m-m-2.md"]
    );
    assert_eq!(
        body(contents(&rendered, "INDEX.md")),
        "- [a–m](INDEX-a-m.md)\n- [m–m](INDEX-m-m.md)\n- [m–m #2](INDEX-m-m-2.md)\n"
    );
}

#[test]
fn every_entry_is_written_exactly_once_under_adversarial_buckets() {
    let mut entries = many('m', 13);
    entries.extend(many('0', 5));
    entries.extend(many('ß', 4));
    entries.extend(many('#', 2));

    let rendered = render(&entries, &config(4));

    let mut file_names = names(&rendered);
    let sorted_names = {
        let mut sorted = file_names.clone();
        sorted.sort_unstable();
        sorted.dedup();
        sorted
    };
    file_names.sort_unstable();
    assert_eq!(
        file_names, sorted_names,
        "duplicate file names would lose entries"
    );

    // `INDEX.md` holds no notes, so the shards alone must account for every entry.
    let mut listed: Vec<String> = Vec::new();
    for (name, _) in rendered.iter().skip(1) {
        listed.extend(titles_in(contents(&rendered, name)));
    }
    // Expected order is the render's own: bucket (`0-9`, `a-z`, then `#` last), then lowercased
    // title. A plain lowercase sort would put `#note` before `0note`, i.e. the `#` bucket first.
    let mut expected: Vec<String> = entries.iter().map(|note| note.title.clone()).collect();
    expected.sort_by(|left, right| {
        bucket_rank(left)
            .cmp(&bucket_rank(right))
            .then_with(|| left.to_lowercase().cmp(&right.to_lowercase()))
    });
    assert_eq!(
        listed.len(),
        expected.len(),
        "an entry was dropped or doubled"
    );
    assert_eq!(listed, expected);
}

#[test]
fn a_non_ascii_first_letter_shares_the_pound_bucket_and_sorts_last() {
    let entries = vec![
        entry("Zebra", "z.md", "1 B", &[], 0, 0),
        entry("Ältestes Archiv", "aeltestes.md", "1 B", &[], 0, 0),
        entry("2026 Review", "2026.md", "1 B", &[], 0, 0),
    ];

    // Unsharded: `#` titles come last, whatever their position in a plain lowercase sort.
    let rendered = render(&entries, &config(600));
    assert_eq!(
        titles_in(contents(&rendered, "INDEX.md")),
        ["2026 Review", "Zebra", "Ältestes Archiv"]
    );

    // Sharded: `#` is its own bucket key, ordered after `z`, and names the shard it lands in.
    // Each digit is its own bucket — the key is the first character itself, so `2026 Review`
    // opens `INDEX-2-2.md` rather than a file named after a character no title starts with.
    let rendered = render(&entries, &config(1));
    assert_eq!(
        names(&rendered),
        ["INDEX.md", "INDEX-2-2.md", "INDEX-z-z.md", "INDEX-#-#.md"]
    );
    assert_eq!(
        body(contents(&rendered, "INDEX.md")),
        "- [2–2](INDEX-2-2.md)\n- [z–z](INDEX-z-z.md)\n- [#–#](INDEX-#-#.md)\n"
    );
}

