#[test]
fn alphabetized_case_insensitive_with_tiebreak() {
    let mut entries = vec![
        entry("cherry", "b/cherry.md", "1 B", &[], 0, 0),
        entry("Banana", "a/banana.md", "1 B", &[], 0, 0),
        entry("apple", "z/apple.md", "1 B", &[], 0, 0),
        // Same title in another casing: `rel` decides, ascending.
        entry("Apple", "a/apple.md", "1 B", &[], 0, 0),
    ];

    let rendered = render(&entries, &config(600));
    assert_eq!(
        titles_in(contents(&rendered, "INDEX.md")),
        ["Apple", "apple", "Banana", "cherry"]
    );

    // The same notes in another order render byte-identically.
    let original = rendered.clone();
    entries.reverse();
    assert_eq!(render(&entries, &config(600)), original);
    for seed in [1_u64, 7, 99, 12345] {
        assert_eq!(
            render(&shuffled(&entries, seed), &config(600)),
            original,
            "seed {seed} changed the output"
        );
    }
}

#[test]
fn wraps_at_hundred_columns() {
    let tags: Vec<String> = (1..=12).map(|index| format!("tag{index}")).collect();
    let crowded = CatalogEntry {
        tags,
        ..entry("Twelve Tags", "inbox/twelve-tags.md", "1.4 KB", &[], 4, 2)
    };

    let rendered = render(&[crowded], &config(600));
    let lines: Vec<&str> = body(contents(&rendered, "INDEX.md")).lines().collect();

    assert!(lines.len() > 1, "twelve tags must wrap: {lines:?}");
    for line in &lines[1..] {
        assert!(
            line.starts_with("  "),
            "continuation without indent: {line:?}"
        );
    }
    for line in &lines {
        assert!(columns(line) <= 100, "{} columns: {line:?}", columns(line));
    }
    // Wrapping only inserts newlines and indents: folding them back reproduces the one-line form.
    assert_eq!(
        body(contents(&rendered, "INDEX.md"))
            .trim_end()
            .replace("\n  ", " "),
        "- [[Twelve Tags]](inbox/twelve-tags.md) · 1.4 KB · #tag1 #tag2 #tag3 #tag4 #tag5 \
         #tag6 #tag7 #tag8 #tag9 #tag10 #tag11 #tag12 · →4 ←2"
    );
}

#[test]
fn exactly_hundred_columns_stays_one_line() {
    let edge = padded_entry(100);
    assert_eq!(columns(&logical_line(&edge)), 100);

    let rendered = render(&[edge], &config(600));
    let lines: Vec<&str> = body(contents(&rendered, "INDEX.md")).lines().collect();

    assert_eq!(
        lines.len(),
        1,
        "a 100-column entry must not wrap: {lines:?}"
    );
}

#[test]
fn one_column_over_breaks_before_the_token() {
    let edge = padded_entry(101);
    assert_eq!(columns(&logical_line(&edge)), 101);

    // `slice::from_ref` rather than `&[edge]`: an array literal moves `edge`, which the
    // `logical_line(&edge)` checks below would then borrow after the move. (`&[edge.clone()]`
    // also works but clippy's `cloned_ref_to_slice_refs` rejects it as a needless clone.)
    let rendered = render(std::slice::from_ref(&edge), &config(600));
    let lines: Vec<&str> = body(contents(&rendered, "INDEX.md")).lines().collect();

    assert_eq!(lines.len(), 2, "101 columns must wrap: {lines:?}");
    assert!(lines[1].starts_with("  "));
    for line in &lines {
        assert!(columns(line) <= 100, "{} columns: {line:?}", columns(line));
    }
    // The break happens before the token that would cross the limit, never inside it. Spec §14
    // orders the fields `… · {tags} · →out ←inc`, so on this entry — budget filled by the tag —
    // the token that crosses is the last one, and it moves whole.
    let tail = logical_line(&edge)
        .rsplit(' ')
        .next()
        .expect("an entry line has spaces")
        .to_string();
    assert_eq!(lines[1], format!("  {tail}"), "the wrapped token was split");
    assert!(!lines[1].trim_start().contains(' '));
    // Wrapping only inserts a newline and the indent: folding them back reproduces one line.
    assert_eq!(
        body(contents(&rendered, "INDEX.md"))
            .trim_end()
            .replace("\n  ", " "),
        logical_line(&edge)
    );
}

#[test]
fn a_token_longer_than_the_limit_is_not_split() {
    let path = format!("dir/{}/leaf.md", "a".repeat(140));
    let deep = entry("Deep", &path, "1 B", &["one", "two"], 0, 0);

    let rendered = render(&[deep], &config(600));
    let lines: Vec<&str> = body(contents(&rendered, "INDEX.md")).lines().collect();

    assert!(lines.len() > 1, "a 140-column path must wrap: {lines:?}");
    let joined = body(contents(&rendered, "INDEX.md"))
        .trim_end()
        .replace("\n  ", " ");
    // Spelled from the same `rel` the entry was built with: the hand-counted literal that stood
    // here held 146 `a`s against a 140-character path, which no renderer can produce. The value
    // asserted is unchanged — the whole logical line, byte for byte.
    assert_eq!(
        joined,
        format!(
            "- [[Deep]]({deep_path}) · 1 B · #one #two · →0 ←0",
            deep_path = path
        )
    );
    assert!(
        lines.iter().any(|line| columns(line) > 100),
        "the over-long token keeps its own line: {lines:?}"
    );
}

