#[test]
fn golden_render_matches_committed_bytes() {
    let rendered = render(&catalog(), &config(4));
    // The goldens are only worth having if they cover both shapes.
    assert_eq!(
        names(&rendered),
        ["INDEX.md", "INDEX-a-m.md", "INDEX-o-v.md"]
    );

    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/golden");
    for (name, contents) in &rendered {
        let path: PathBuf = dir.join(name);
        let committed = fs::read(&path)
            .unwrap_or_else(|err| panic!("missing golden {}: {err}", path.display()));
        assert_eq!(
            committed.as_slice(),
            contents.as_bytes(),
            "golden drift in {name}"
        );
    }

    // A golden that is no longer produced is drift of another kind: the shard set changed.
    let mut committed: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|err| panic!("cannot read {}: {err}", dir.display()))
        .map(|entry| {
            entry
                .expect("unreadable golden directory entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    committed.sort();
    let mut produced = names(&rendered);
    produced.sort_unstable();
    assert_eq!(committed, produced, "tests/golden and the render disagree");
}
