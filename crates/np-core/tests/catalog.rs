//! Catalog render: entries in, `(filename, contents)` pairs out.
//!
//! Nothing here touches the filesystem except the committed goldens, because rendering is pure —
//! Task 10 owns writing the files atomically and deleting the ones that disappeared. What this
//! file pins down is the property that makes the catalog usable as a human artefact: **the same
//! entries always produce the same bytes**, so a regeneration diff shows only real changes and
//! never a timestamp, a hash-map order or a shuffled input order.
//!
//! The rules under test (spec §14 line format, §10 determinism):
//!
//! - one entry per note, `- [[title]](rel) · size · tags · →out ←inc`, wrapped at 100 columns;
//! - total order: lowercased title, tie-broken by `rel`, independent of input order;
//! - past `max_entries_per_file` the catalog shards by the title's first letter, and `INDEX.md`
//!   becomes a list of shard links holding no note entries at all.

use std::fs;
use std::path::{Path, PathBuf};

use unicode_width::UnicodeWidthStr;

use np_core::catalog::{render, size_human, CatalogEntry};
use np_core::config::CatalogConfig;

/// The fixed prologue every generated file carries, so a shard opened on its own says what it is.
const HEADER: &str = "# INDEX\n_generated by note-processor; do not edit_\n";

/// One entry in the shape [`render`] consumes, spelled compactly enough that a test reads as the
/// data it is about.
fn entry(title: &str, rel: &str, size: &str, tags: &[&str], out: u32, inc: u32) -> CatalogEntry {
    CatalogEntry {
        title: title.to_string(),
        rel: rel.to_string(),
        // The order tie-break, which nothing renders. For these fixtures the byte key is the display text's
        // own bytes, exactly as a walk would record them for an ASCII or valid-UTF-8 name (F13 §3).
        rel_bytes: rel.as_bytes().to_vec(),
        size_human: size.to_string(),
        tags: tags.iter().map(|tag| (*tag).to_string()).collect(),
        out,
        inc,
    }
}

