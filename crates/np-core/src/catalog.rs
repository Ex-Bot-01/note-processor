//! Catalog render: [`CatalogEntry`] values in, `(filename, contents)` pairs out.
//!
//! Rendering is pure — Task 10 owns writing the files and deleting the ones that disappeared —
//! so the whole contract of this module is that equal entries produce equal bytes. Nothing here
//! reads a clock, a locale or a hash map: entries are put in one total order, wrapped by a fixed
//! column budget and split by a configured threshold, which makes a regeneration diff show real
//! changes only (spec §10, line format §14).

use unicode_width::UnicodeWidthStr;

use crate::config::CatalogConfig;
use crate::index_names;

/// Fixed prologue of every generated file, so a shard opened on its own still says what it is.
///
/// Public because it is also the fingerprint [`crate::scan::scan`] deletes by: a file that does not open
/// with these bytes — in either their LF spelling or the `HEADER_CRLF` one below, because line endings
/// carry no identity — was not published here, whatever it is called (spec §7). The two spellings are
/// alternatives, not a licence to be generous: any other difference in those two lines, a half-converted
/// header included, answers the same question as a foreign file.
pub const HEADER: &str = "# INDEX\n_generated by note-processor; do not edit_\n";
/// [`HEADER`] with Windows line endings — the one rewrite of it this program treats as still being ours.
///
/// Line endings carry no identity: a checkout, an editor or a sync tool can turn every `\n` of a
/// published shard into `\r\n` without touching a word of the catalog, and the file is still the one this
/// program wrote. [`mod@crate::scan`] accepts either spelling as its deletion fingerprint.
pub(crate) const HEADER_CRLF: &str = "# INDEX\r\n_generated by note-processor; do not edit_\r\n";
/// Columns a rendered line may occupy before the next token moves to a continuation line. A column
/// is a terminal cell, not a character — [`wrap`] measures them.
const COLUMN_LIMIT: usize = 100;
/// Size units, whole bytes up to 1 KiB and one decimal from there on; GB is the largest unit.
const UNITS: [&str; 4] = ["B", "KB", "MB", "GB"];
/// Bucket for a title whose first character is not an ASCII letter or digit; sorted last.
const OTHER_BUCKET: char = '#';

/// One note as the catalog sees it. Everything is pre-formatted by the caller — in particular
/// `size_human` — because the catalog must not decide what a byte count looks like twice.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CatalogEntry {
    /// Link text: the note's title, or its file name when it has no title.
    pub title: String,
    /// Workspace-relative path, already in the `/`-separated spelling used inside markdown.
    pub rel: String,
    /// Human size, e.g. `9 B` or `1.4 KB`; see [`size_human`].
    pub size_human: String,
    /// Tags in display order; rendered as `#tag` tokens, or `—` when the list is empty.
    pub tags: Vec<String>,
    /// Number of links this note holds.
    pub out: u32,
    /// Number of links pointing at this note.
    pub inc: u32,
}

/// Byte count in the catalog's spelling: whole bytes below 1 KiB, then one decimal in KB/MB/GB.
///
/// The unit changes at the power of two, so `1023 B` stays whole bytes while `1024` is already
/// `1.0 KB`. GB is the last unit: a petabyte-sized file grows the number instead of inventing a
/// unit, which keeps every size the same shape.
pub fn size_human(bytes: u64) -> String {
    if bytes < 1024 {
        return format!("{bytes} B");
    }
    let mut value = bytes as f64 / 1024.0;
    let mut unit = 1;
    while unit + 1 < UNITS.len() && value >= 1024.0 {
        value /= 1024.0;
        unit += 1;
    }
    format!("{value:.1} {}", UNITS[unit])
}

/// Render the catalog: `INDEX.md` first, then its shards when the entry count passes
/// `cfg.max_entries_per_file`.
///
/// The order is total and input-order independent — lowercased title, then `rel` — so a shuffled
/// corpus renders byte-identically. Once sharded, `INDEX.md` holds only shard links and every
/// entry lands in exactly one shard; file names are made unique by a positional suffix, because a
/// bucket larger than the threshold would otherwise produce several `INDEX-m-m.md` files and
/// silently overwrite all but one. Every name comes from [`crate::index_names`], which owns the spelling.
pub fn render(entries: &[CatalogEntry], cfg: &CatalogConfig) -> Vec<(String, String)> {
    let mut ordered: Vec<&CatalogEntry> = entries.iter().collect();
    ordered.sort_by(|left, right| sort_key(left).cmp(&sort_key(right)));

    let lines: Vec<String> = ordered
        .iter()
        .map(|entry| wrap(&entry_line(entry), cfg.continuation_indent))
        .collect();

    let per_file = cfg.max_entries_per_file.max(1);
    if lines.len() <= per_file {
        return vec![(index_names::ENTRY.to_string(), file(&lines))];
    }

    // `seen` counts how often one bucket range already occurred; a repeat gets the occurrence number
    // appended to its shard name so no shard is written over an earlier one. The key is the pair of bucket
    // characters, not a spelled-out range: the name itself is built by [`crate::index_names`], which owns
    // that spelling. A vector rather than a map keeps the render path free of iteration order that could
    // leak into the bytes.
    let mut seen: Vec<((char, char), usize)> = Vec::new();
    let mut links: Vec<String> = Vec::new();
    let mut shards: Vec<(String, String)> = Vec::new();

    for (entry_chunk, line_chunk) in ordered.chunks(per_file).zip(lines.chunks(per_file)) {
        let first = bucket_key(&entry_chunk[0].title);
        let last = bucket_key(&entry_chunk[entry_chunk.len() - 1].title);
        let occurrence = match seen.iter_mut().find(|(range, _)| *range == (first, last)) {
            Some(entry) => {
                entry.1 += 1;
                entry.1
            }
            None => {
                seen.push(((first, last), 1));
                1
            }
        };
        let name = index_names::shard_name(first, last, occurrence);
        let label = if occurrence == 1 {
            format!("[{first}\u{2013}{last}]")
        } else {
            format!("[{first}\u{2013}{last} #{occurrence}]")
        };

        links.push(format!("- {label}({name})"));
        shards.push((name, file(line_chunk)));
    }

    let mut rendered = Vec::with_capacity(shards.len() + 1);
    rendered.push((index_names::ENTRY.to_string(), file(&links)));
    rendered.extend(shards);
    rendered
}

/// Sort position of an entry: bucket, then lowercased title, then `rel`.
fn sort_key(entry: &CatalogEntry) -> (u8, String, &str) {
    (
        bucket_rank(bucket_key(&entry.title)),
        entry.title.to_lowercase(),
        &entry.rel,
    )
}

/// The bucket a title belongs to: its first character lowercased when that is ASCII `[0-9a-z]`,
/// otherwise `#`.
fn bucket_key(title: &str) -> char {
    match title.chars().next().map(|c| c.to_ascii_lowercase()) {
        Some(letter) if letter.is_ascii_alphanumeric() => letter,
        _ => OTHER_BUCKET,
    }
}

/// Bucket order: `0-9`, then `a-z`, then `#`.
fn bucket_rank(bucket: char) -> u8 {
    if bucket.is_ascii_digit() {
        bucket as u8 - b'0'
    } else if bucket.is_ascii_lowercase() {
        10 + bucket as u8 - b'a'
    } else {
        36
    }
}

/// The one-line rendering of an entry, before wrapping.
fn entry_line(entry: &CatalogEntry) -> String {
    let tags = if entry.tags.is_empty() {
        "—".to_string()
    } else {
        entry
            .tags
            .iter()
            .map(|tag| format!("#{tag}"))
            .collect::<Vec<_>>()
            .join(" ")
    };
    format!(
        "- [[{}]]({}) · {} · {tags} · →{} ←{}",
        entry.title, entry.rel, entry.size_human, entry.out, entry.inc
    )
}

/// Wrap one logical line at [`COLUMN_LIMIT`] columns: break before the token that would cross
/// the limit, indent continuation lines by `indent` spaces. The budget counts the rendered line, so a
/// continuation line has its indent deducted before the first token. A token longer than the limit is
/// kept whole on a line of its own rather than split.
///
/// Width is measured in display columns (UAX #11, via `unicode-width`), not characters: a CJK
/// ideograph or emoji occupies two columns and a combining mark none, so counting characters let a
/// non-ASCII title overflow the budget by roughly one column per wide character. The measurement
/// reads nothing but these bytes — no terminal, locale or environment — which is what keeps a
/// regeneration byte-stable (spec §10). Ambiguous-width characters (`·`, `—`, `→`) count one, the
/// non-CJK spelling; choosing the other one would rewrite every committed golden.
fn wrap(line: &str, indent: usize) -> String {
    let mut lines: Vec<String> = Vec::new();
    for token in line.split(' ') {
        // A continuation line spends `indent` columns on its prefix before its first token, so those
        // columns are already gone when deciding whether the next token still fits. Leaving the prefix
        // out of the budget let a wrapped entry reach `COLUMN_LIMIT + indent` on screen — 101 visible
        // columns against a 100-column promise.
        let prefix = if lines.len() > 1 { indent } else { 0 };
        let current = lines.last_mut();
        match current {
            None => lines.push(token.to_string()),
            Some(current) => {
                let width = current.width() + prefix + 1 + token.width();
                if width > COLUMN_LIMIT {
                    lines.push(token.to_string());
                } else {
                    current.push(' ');
                    current.push_str(token);
                }
            }
        }
    }

    let indent: String = " ".repeat(indent);
    let mut out = lines[0].clone();
    for line in &lines[1..] {
        out.push('\n');
        out.push_str(&indent);
        out.push_str(line);
    }
    out
}

/// A complete generated file: header, blank line, body. An empty body adds no blank line, so
/// every file ends with exactly one `\n`.
fn file(lines: &[String]) -> String {
    let mut out = String::from(HEADER);
    if lines.is_empty() {
        return out;
    }
    out.push('\n');
    for line in lines {
        out.push_str(line);
        out.push('\n');
    }
    out
}
